/**
 * INTERNAL expert-reference challenge contract.
 *
 * Only cases approved by an identified qualified reviewer may be compared.
 * A reference case is a controlled hypothesis about a specific workflow,
 * not a universal list of hazards or a claim of regulatory compliance.
 */
export type ReviewedConditionObservation = {
  conditionId: string;
  /** "present" is a recorded reviewer observation, not an AI inference. */
  state: "present" | "absent" | "unknown";
  observedEvidenceIds: string[];
  reviewedBy: string | null;
  reviewedAt: string | null;
};

export type ReferenceHazardExpectation = {
  id: string;
  clinicalReason: string;
  potentialHarm: string;
  /** All these reviewed conditions must be present before checking coverage. */
  appliesWhenAllConditions: string[];
  evidenceIds: string[];
};

export type ReferenceInteractionExpectation = {
  id: string;
  conditionIds: string[];
  referenceHazardIds: string[];
  failureMechanism: string;
  potentialHarm: string;
  evidenceIds: string[];
};

export type ExpertReferenceCase = {
  id: string;
  version: string;
  intendedContextId: string;
  status: "draft" | "expert-reviewed";
  reviewerId: string | null;
  reviewedAt: string | null;
  referenceEvidenceIds: string[];
  expectedHazards: ReferenceHazardExpectation[];
  expectedInteractions: ReferenceInteractionExpectation[];
};

export type HazardMapping = {
  referenceHazardId: string;
  assessmentHazardId: string;
  reviewerId: string | null;
  reviewedAt: string | null;
  evidenceIds: string[];
};

export type InteractionTrace = {
  referenceInteractionId: string;
  /** Explicitly recorded impacted hazards and mitigating controls. */
  assessmentHazardIds: string[];
  controlIds: string[];
  reviewerId: string | null;
  reviewedAt: string | null;
  rationale: string;
  evidenceIds: string[];
};

export type ReferenceChallengeInput = {
  contextId: string;
  hazards: { id: string; description: string; potentialHarm: string }[];
  controls: { id: string; hazardIds: string[] }[];
  evidence: { id: string }[];
  reference: ExpertReferenceCase;
  observations: ReviewedConditionObservation[];
  hazardMappings: HazardMapping[];
  interactionTraces: InteractionTrace[];
};

export type ReferenceChallengeFinding = {
  criterionId: "SDC-02" | "SDC-06";
  status: "potential-concern" | "identified-inconsistency" | "evidence-insufficient" | "requires-qualified-review";
  referenceId: string;
  rationale: string;
  requiredAction: string;
  /** No text-based hazard classification is generated by the engine. */
  evidenceIds: string[];
};

export type ReferenceChallengeResult = {
  ruleSetVersion: "0.1.1";
  comparisonStatus: "blocked" | "requires-review";
  /** The engine never gives a "complete" finding or an acceptability judgement. */
  coverageConclusion: "not-determined";
  findings: ReferenceChallengeFinding[];
  blockers: string[];
};
